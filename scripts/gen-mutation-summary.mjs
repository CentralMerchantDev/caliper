// GENERATES test/mutationSummary.generated.json
//
// PART 7b/E2 (docs/WORLD-BUILD-PLAN.md): test/.mutate-results.json -- the
// only record that every control in test/mutations.json has actually been
// RUN, not just written -- is gitignored, on purpose (scripts/mutate.mjs's
// own comment calls it "a progress file, not a project artefact": it is
// written after every single mutation so a killed run loses at most one
// result, and committing that churn would make every local run dirty the
// tree for no reason).
//
// The consequence nobody had named until now: a fresh clone of this repo
// gets 0 of 80 rows of evidence for the one claim this project's mutation
// discipline exists to support -- "every control has been shown to catch
// something, for real, at least once." That is not a progress file's
// problem to fix. It is a missing generated artefact, the same shape as
// scripts/gen-test-count.mjs and scripts/gen-city-summary.mjs: run the real
// thing (mutate.mjs / _mutcheck.mjs), keep the noisy day-to-day record
// local, and commit a small, checkable SUMMARY of what it proved.
//
//   node scripts/gen-mutation-summary.mjs
//
// Refuses to publish (non-zero exit, but still WRITES the honest measured
// file -- a bad measurement is not a reason to hide it, same rule
// gen-test-count.mjs follows) if any manifest id has never been run, or has
// a status other than CAUGHT. Either is real evidence something is wrong,
// not a reason to look away from it.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST_PATH = join(ROOT, "test", "mutations.json");
const RESULTS_PATH = join(ROOT, "test", ".mutate-results.json");
const OUT_PATH = join(ROOT, "test", "mutationSummary.generated.json");

if (!existsSync(RESULTS_PATH)) {
  console.error(
    `no ${RESULTS_PATH} -- nothing has been run yet. Run the mutation suite ` +
    "first (scripts/mutate.mjs --all, or scripts/_mutcheck.mjs per control), then regenerate.",
  );
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8")).mutations;
const resultsState = JSON.parse(readFileSync(RESULTS_PATH, "utf8"));
const byId = new Map(resultsState.results.map((r) => [r.id, r]));

const missing = [];
const notCaught = [];
const entries = manifest.map((m) => {
  const r = byId.get(m.id);
  if (!r) { missing.push(m.id); return { id: m.id, status: "NEVER RUN" }; }
  if (r.status !== "CAUGHT") notCaught.push(m.id);
  // measuredAt/method are not recorded by test/.mutate-results.json today --
  // PART 7 Phase M/M1 ("every row carrying measuredAt and method") is the
  // full re-run that adds them going forward. Recorded as null here rather
  // than guessed, backdated, or silently omitted -- an absent field says
  // "not captured", which is true; a fabricated one would not be.
  return { id: r.id, status: r.status, measuredAt: r.measuredAt ?? null, method: r.method ?? null };
});

const payload = {
  _comment:
    "GENERATED by scripts/gen-mutation-summary.mjs -- do not edit by hand. " +
    "The committed evidence that every mutation in test/mutations.json has actually been " +
    "run, not just written -- test/.mutate-results.json (the full record, with find/replace/ " +
    "guards text) is gitignored on purpose; this is the small, checkable summary of it. " +
    "measuredAt/method are null for rows recorded before PART 7b/E2 added this file -- " +
    "see PART 7 Phase M/M1 for the full re-run that will backfill them for real.",
  generatedAt: new Date().toISOString().slice(0, 10),
  manifestCount: manifest.length,
  resultsCount: resultsState.results.length,
  caught: entries.filter((e) => e.status === "CAUGHT").length,
  survived: entries.filter((e) => e.status === "SURVIVED").length,
  inconclusive: entries.filter((e) => e.status === "INCONCLUSIVE").length,
  neverRun: missing,
  mutations: entries,
};

writeFileSync(OUT_PATH, JSON.stringify(payload, null, 2) + "\n");
console.log(
  `wrote test/mutationSummary.generated.json: ${payload.caught} of ${payload.manifestCount} CAUGHT, ` +
  `${payload.survived} SURVIVED, ${payload.inconclusive} INCONCLUSIVE, ${missing.length} never run`,
);

if (missing.length || notCaught.length) {
  console.error(
    "\n### NOT every control is proven. The file above was still written -- a bad\n" +
    "### measurement is not a reason to hide it -- but this exits non-zero because\n" +
    "### the claim \"every control has been shown to catch something\" is false right now.\n" +
    (missing.length ? `### never run: ${missing.join(", ")}\n` : "") +
    (notCaught.length ? `### not CAUGHT: ${notCaught.join(", ")}\n` : ""),
  );
  process.exit(1);
}
