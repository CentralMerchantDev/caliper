// =============================================================================
// I3 (docs/BUILD-LOOP.md Step 2 plan, approved 2026-09-08) -- generate
// docs/MODULE-MAP.md from the real module graph: every module, its exports,
// and who calls each one. Read this before proposing to build a capability --
// docs/AUDIT-PROTOCOL.md's nine recorded pattern-E failures all shipped work
// beside a capability nobody checked already existed.
//
// Reuses buildReverseMap (scripts/lib/module-graph.mjs), the same function
// test/deadExports.test.ts runs the gate from -- one graph, two consumers,
// not a second implementation of "who calls what" for a document instead of
// a test.
//
//   node scripts/gen-module-map.mjs
// =============================================================================
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { loadModuleFiles, buildReverseMap, isTestPath, displayPath } from "./lib/module-graph.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");
const SRC = join(ROOT, "src");
const TEST = join(ROOT, "test");
const OUT_PATH = join(ROOT, "docs", "MODULE-MAP.md");
const ALLOWLIST_PATH = join(ROOT, "test", "deadExports.allowlist.json");

function loadAllowlist() {
  if (!existsSync(ALLOWLIST_PATH)) return {};
  const raw = JSON.parse(readFileSync(ALLOWLIST_PATH, "utf8"));
  return raw.entries || {};
}

export function renderModuleMap(files, { root = ROOT, allowlist = {} } = {}) {
  const map = buildReverseMap(files, isTestPath);
  const modulePaths = [...map.keys()].sort((a, b) => displayPath(root, a).localeCompare(displayPath(root, b)));

  let totalExports = 0, totalCalled = 0, totalTestOnly = 0, totalDead = 0;

  const lines = [];
  lines.push("<!-- GENERATED by scripts/gen-module-map.mjs -- do not edit by hand. -->");
  lines.push("# Module map");
  lines.push("");
  lines.push(
    "Every export in `public/` and `src/` (excluding `public/vendor/` and " +
    "`*.generated.ts`), and every file that imports it. Read this before " +
    "proposing to build a capability -- `docs/AUDIT-PROTOCOL.md`'s nine " +
    "recorded pattern-E failures all shipped work beside a capability nobody " +
    "checked already existed.",
  );
  lines.push("");
  lines.push(
    "`UNCALLED` means no other file (besides tests) imports this export by " +
    "name. It does not always mean dead: a function reached only through a " +
    "dispatch table defined in its own file (never imported by name from " +
    "elsewhere) reads the same way here as one nobody reaches at all -- see " +
    "`test/deadExports.allowlist.json`'s own header for that distinction, " +
    "and `test/deadExports.test.ts` (the gate this map shares its data with).",
  );
  lines.push("");
  lines.push("---");
  lines.push("");

  for (const filePath of modulePaths) {
    const exportsByName = map.get(filePath);
    if (exportsByName.size === 0) continue; // a file with no exports has nothing to map
    const rel = displayPath(root, filePath);
    lines.push(`## \`${rel}\``);
    lines.push("");
    const names = [...exportsByName.keys()].sort();
    for (const name of names) {
      const entry = exportsByName.get(name);
      totalExports++;
      if (entry.callers.size > 0) {
        totalCalled++;
        const callers = [...entry.callers].map((c) => displayPath(root, c)).sort();
        lines.push(`- \`${name}\` -- called from ${callers.map((c) => `\`${c}\``).join(", ")}`);
      } else {
        const key = `${rel}:${name}`;
        const reason = allowlist[key];
        if (entry.testCallers.size > 0) {
          const testCallers = [...entry.testCallers].map((c) => displayPath(root, c)).sort();
          totalTestOnly++;
          lines.push(
            `- \`${name}\` -- **UNCALLED** (imported only by test${testCallers.length === 1 ? "" : "s"}: ` +
            `${testCallers.map((c) => `\`${c}\``).join(", ")})${reason ? ` -- *${reason}*` : ""}`,
          );
        } else {
          totalDead++;
          lines.push(`- \`${name}\` -- **UNCALLED**${reason ? ` -- *${reason}*` : ""}`);
        }
      }
    }
    lines.push("");
  }

  lines.unshift(
    "<!-- COUNTS: " +
    `modules=${modulePaths.filter((p) => map.get(p).size > 0).length} ` +
    `exports=${totalExports} called=${totalCalled} testOnly=${totalTestOnly} dead=${totalDead}` +
    " -->",
  );

  return { text: lines.join("\n") + "\n", counts: { modules: modulePaths.filter((p) => map.get(p).size > 0).length, exports: totalExports, called: totalCalled, testOnly: totalTestOnly, dead: totalDead } };
}

// Only runs the write when invoked directly (`node scripts/gen-module-map.mjs`),
// not when imported by a test for renderModuleMap's own direct tests.
//
// NOT an import.meta.url comparison against process.argv[1] -- that broke
// the moment this module was bundled (esbuild --bundle, as test/run.mjs and
// scripts/_mutcheck.mjs both do to run test/genModuleMap.test.ts): once
// inlined into another file's bundle, this module's import.meta.url stops
// referring to gen-module-map.mjs's own path and instead reflects the
// bundle's, so the comparison silently started matching the TEST run too,
// and the smoke test's first _mutcheck.mjs invocation tried to write
// docs/MODULE-MAP.md relative to a ROOT computed from inside test/.built/.
// process.argv[1] is set once by Node's own process launcher and is
// unaffected by bundling; checking it directly is simpler AND correct where
// the cleverer check was neither.
if (process.argv[1] && process.argv[1].replace(/\\/g, "/").endsWith("/gen-module-map.mjs")) {
  const files = loadModuleFiles({ publicDir: PUBLIC, srcDir: SRC, testDir: TEST });
  const allowlist = loadAllowlist();
  const { text, counts } = renderModuleMap(files, { root: ROOT, allowlist });
  const before = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : null;
  writeFileSync(OUT_PATH, text);
  console.log(
    `docs/MODULE-MAP.md: ${counts.modules} modules, ${counts.exports} exports ` +
    `(${counts.called} called, ${counts.testOnly} test-only, ${counts.dead} fully uncalled). ` +
    `${before === text ? "unchanged" : "CHANGED"}`,
  );
}
