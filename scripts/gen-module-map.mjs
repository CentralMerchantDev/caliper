// =============================================================================
// I3 (docs/BUILD-LOOP.md Step 2 plan, approved 2026-09-08), UPGRADED to
// reachability the same day (Mark's review) -- generate docs/MODULE-MAP.md
// from the real module graph: every module, its exports, and whether each
// is reachable from PRODUCT, DEMO-only, TEST-only, or nothing at all. Read
// this before proposing to build a capability -- docs/AUDIT-PROTOCOL.md's
// nine recorded pattern-E failures all shipped work beside a capability
// nobody checked already existed.
//
// Reuses classifyRepoReachability (scripts/lib/module-graph.mjs), the exact
// same pipeline test/deadExports.test.ts runs the gate from -- one
// classification, two consumers, not a second implementation of "who calls
// what, and does it matter" for a document instead of a test.
//
//   node scripts/gen-module-map.mjs
// =============================================================================
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { displayPath, classifyRepoReachability } from "./lib/module-graph.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = join(ROOT, "public");
const SRC = join(ROOT, "src");
const TEST = join(ROOT, "test");
const WRANGLER_PATH = join(ROOT, "wrangler.jsonc");
const OUT_PATH = join(ROOT, "docs", "MODULE-MAP.md");
const ALLOWLIST_PATH = join(ROOT, "test", "deadExports.allowlist.json");

function loadAllowlist() {
  if (!existsSync(ALLOWLIST_PATH)) return {};
  const raw = JSON.parse(readFileSync(ALLOWLIST_PATH, "utf8"));
  return raw.entries || {};
}

const STATE_LABEL = {
  product: null, // no marker -- the module map's whole point is to make PRODUCT the unremarkable, default-looking case
  "demo-only": "**DEMO-ONLY**",
  "test-only": "**TEST-ONLY**",
  unreachable: "**UNREACHABLE**",
};

export function renderModuleMap(classified, { root = ROOT, allowlist = {} } = {}) {
  const modulePaths = [...classified.keys()].sort((a, b) => displayPath(root, a).localeCompare(displayPath(root, b)));
  const counts = { product: 0, "demo-only": 0, "test-only": 0, unreachable: 0 };

  const lines = [];
  lines.push("<!-- GENERATED by scripts/gen-module-map.mjs -- do not edit by hand. -->");
  lines.push("# Module map");
  lines.push("");
  lines.push(
    "Every export in `public/` and `src/` (excluding `public/vendor/` and " +
    "`*.generated.ts`), classified by REACHABILITY -- not just \"does anything " +
    "import this\", which cannot distinguish real usage from a demo page " +
    "nothing else loads. Read this before proposing to build a capability -- " +
    "`docs/AUDIT-PROTOCOL.md`'s nine recorded pattern-E failures all shipped " +
    "work beside a capability nobody checked already existed.",
  );
  lines.push("");
  lines.push(
    "**PRODUCT** (no marker below) is reachable from wrangler.jsonc's `\"main\"` " +
    "or the module scripts in `public/index.html`/`public/city.html` -- what a " +
    "visitor's browser or the Worker itself actually runs. **DEMO-ONLY** has a " +
    "real caller, but that caller is only ever reached from one of the OTHER " +
    "html pages in `public/` -- roadkit.js's `junction` and `roundabout` are " +
    "this shape: called from `public/roadkit-street-demo.js`, which nothing " +
    "else imports. **TEST-ONLY** is reachable only from `test/`. " +
    "**UNREACHABLE** has no caller reachable from anywhere. See " +
    "`test/deadExports.allowlist.json`'s own header for the full reasoning, " +
    "and `test/deadExports.test.ts` (the gate this map shares its data with).",
  );
  lines.push("");
  lines.push("---");
  lines.push("");

  for (const filePath of modulePaths) {
    const exportsByName = classified.get(filePath);
    if (exportsByName.size === 0) continue; // a file with no exports has nothing to map
    const rel = displayPath(root, filePath);
    lines.push(`## \`${rel}\``);
    lines.push("");
    const names = [...exportsByName.keys()].sort();
    for (const name of names) {
      const entry = exportsByName.get(name);
      counts[entry.state]++;
      const key = `${rel}:${name}`;
      const reason = allowlist[key];
      if (entry.state === "product") {
        const via = typeof entry.via === "string" && entry.via !== "wrangler.jsonc" ? displayPath(root, entry.via) : entry.via;
        lines.push(`- \`${name}\` -- called from \`${via}\``);
      } else {
        const via = entry.via ? (entry.via === "wrangler.jsonc" ? "wrangler.jsonc" : displayPath(root, entry.via)) : null;
        lines.push(
          `- \`${name}\` -- ${STATE_LABEL[entry.state]}${via ? ` (via \`${via}\`)` : ""}` +
          `${reason ? ` -- *${reason}*` : ""}`,
        );
      }
    }
    lines.push("");
  }

  const moduleCount = modulePaths.filter((p) => classified.get(p).size > 0).length;
  const totalExports = counts.product + counts["demo-only"] + counts["test-only"] + counts.unreachable;
  lines.unshift(
    "<!-- COUNTS: " +
    `modules=${moduleCount} exports=${totalExports} product=${counts.product} ` +
    `demoOnly=${counts["demo-only"]} testOnly=${counts["test-only"]} unreachable=${counts.unreachable}` +
    " -->",
  );

  return {
    text: lines.join("\n") + "\n",
    counts: { modules: moduleCount, exports: totalExports, ...counts },
  };
}

// Only runs the write when invoked directly (`node scripts/gen-module-map.mjs`),
// not when imported by a test for renderModuleMap's own direct tests.
//
// NOT an import.meta.url comparison against process.argv[1] -- that broke
// the moment this module was bundled (esbuild --bundle, as test/run.mjs and
// scripts/_mutcheck.mjs both do to run test/genModuleMap.test.ts): once
// inlined into another file's bundle, this module's import.meta.url stops
// referring to gen-module-map.mjs's own path and instead reflects the
// bundle's, so the comparison silently started matching the TEST run too.
// process.argv[1] is set once by Node's own process launcher and is
// unaffected by bundling; checking it directly is simpler AND correct where
// the cleverer check was neither.
if (process.argv[1] && process.argv[1].replace(/\\/g, "/").endsWith("/gen-module-map.mjs")) {
  const wranglerText = readFileSync(WRANGLER_PATH, "utf8");
  const { classified } = classifyRepoReachability({ publicDir: PUBLIC, srcDir: SRC, testDir: TEST, repoRoot: ROOT, wranglerText });
  const allowlist = loadAllowlist();
  const { text, counts } = renderModuleMap(classified, { root: ROOT, allowlist });
  const before = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : null;
  writeFileSync(OUT_PATH, text);
  console.log(
    `docs/MODULE-MAP.md: ${counts.modules} modules, ${counts.exports} exports ` +
    `(${counts.product} product, ${counts["demo-only"]} demo-only, ${counts["test-only"]} test-only, ${counts.unreachable} unreachable). ` +
    `${before === text ? "unchanged" : "CHANGED"}`,
  );
}
