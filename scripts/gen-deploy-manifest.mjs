// GENERATES test/deployManifest.generated.json and public/overview-scene.html's
// own #deploy-version/#deploy-commit/#deploy-build-time spans.
//
// SHIP-5 (docs/briefs/BLD-2026-09-17.md §5): "a deploy manifest -- version,
// commit, build time, on the page, with a test asserting the page's declared
// commit matches what built it. A manifest nothing checks is decoration."
//
// Same pattern as scripts/gen-test-count.mjs: run the real thing (here,
// `git rev-parse HEAD` and package.json's own version, not invented), write
// the result, patch the page's own spans via an anchored regex, exit 1 if a
// span is missing rather than silently leaving the page stale.
//
//   node scripts/gen-deploy-manifest.mjs
//
// THE COMMIT THIS EMBEDS IS THE PARENT, NOT A PREDICTION OF ITS OWN COMMIT --
// AND THAT IS CORRECT, NOT A BUG.
//
// This script runs BEFORE the commit that carries its own output is made, so
// `git rev-parse HEAD` here reads the CURRENT HEAD -- the commit this page
// was actually built from -- never the not-yet-created commit that will add
// this very change (which cannot be known in advance; embedding a
// self-referential hash is not possible). test/deployManifest.test.ts's own
// gate does not assert string equality against the CURRENT HEAD at test
// time either, for the same reason: that would break the instant this
// generator's own commit lands (HEAD moves, the embedded hash does not, by
// construction). It asserts the declared commit is a REAL commit that is
// HEAD or an ancestor of HEAD -- "this page was genuinely built from a real
// point in this repo's own history," which is the checkable claim "matches
// what built it" actually supports without asking this file to predict a
// hash that does not exist yet.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const commit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim();
const shortCommit = commit.slice(0, 7);
const version = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).version;
// ISO, truncated to the minute -- a real, generation-time wall-clock
// reading (Date.now(), not invented or copied from elsewhere), not a
// claim that a CI pipeline stamped it (this repo has none -- confirmed
// directly, no .github/workflows exist -- so "build time" here honestly
// means "the last time this generator actually ran", the same trust
// level test/testCount.generated.json's own generatedAt already has).
const buildTime = new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC";

const record = {
  _comment: "GENERATED by scripts/gen-deploy-manifest.mjs -- do not edit by hand. public/overview-scene.html's own #deploy-* spans are checked against this by test/deployManifest.test.ts.",
  version,
  commit,
  shortCommit,
  buildTime,
};
writeFileSync(join(ROOT, "test", "deployManifest.generated.json"), JSON.stringify(record, null, 2) + "\n");

const page = join(ROOT, "public", "overview-scene.html");
let html = readFileSync(page, "utf8");
const before = html;
const claims = [
  ["deploy-version", version],
  ["deploy-commit", shortCommit],
  ["deploy-build-time", buildTime],
];
const missing = [];
for (const [id, value] of claims) {
  // Anchored on the id -- if the markup is restructured this reports it
  // rather than silently writing nothing and leaving the page stale, the
  // same discipline gen-test-count.mjs's own regex already uses.
  const re = new RegExp(`(<span id="${id}">)[^<]*(</span>)`);
  if (!re.test(html)) { missing.push(id); continue; }
  html = html.replace(re, `$1${value}$2`);
}
if (missing.length) {
  console.error(
    `\n### could not find ${missing.join(" or ")} in public/overview-scene.html.\n` +
    "### The manifest was recorded but the PAGE was not updated, which is exactly\n" +
    "### the stale claim test/deployManifest.test.ts will fail on. Fix the markup\n" +
    "### or this script -- do not just edit the spans by hand.",
  );
  process.exit(1);
}
if (html !== before) {
  writeFileSync(page, html);
  console.log(`updated public/overview-scene.html: v${version} · ${shortCommit} · ${buildTime}`);
} else {
  console.log("public/overview-scene.html already agreed with the measurement");
}
