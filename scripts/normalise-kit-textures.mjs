// NORMALISE KIT TEXTURES -- offline, run once, committed.
//
// C1.6, corrected 2026-09-14: a DataArrayTexture requires every layer to
// share one resolution and format. Source packs do not agree on either
// (Kenney ships PNG, the vendored ground texture is WebP; sizes happen to
// match today but are not guaranteed to stay that way as more packs are
// added). This script is the one place that dependency is paid off, so nothing
// at runtime has to reconcile mismatched sources.
//
// Run: node scripts/normalise-kit-textures.mjs
// Output: public/vendor/kits/array-texture/<NN>-<name>.png, all identical
// width/height/format (RGBA PNG), plus a manifest naming which layer index
// each file became -- the runtime scene reads the manifest, never
// hardcodes an index.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "public/vendor/kits/array-texture");
const TARGET_SIZE = 512; // matches every source pack today; the point of this script is that it would not need to.

const SOURCES = [
  {
    name: "kenney-modular-buildings",
    path: "public/vendor/kits/kenney-modular-buildings/Textures/colormap.png",
    usedBy: [
      "building-sample-house-a.glb", "building-sample-house-b.glb", "building-sample-house-c.glb",
      "building-sample-tower-a.glb", "building-sample-tower-b.glb", "building-sample-tower-c.glb", "building-sample-tower-d.glb",
    ],
  },
  {
    name: "kenney-city-kit-roads",
    path: "public/vendor/kits/kenney-city-kit-roads/Textures/colormap.png",
    usedBy: ["road-straight.glb", "road-bend.glb", "road-crossing.glb", "light-square.glb", "electricity-pole.glb", "dumpster.glb"],
  },
  {
    // Added for L12 (docs/briefs/OVERNIGHT-BLD-2026-09-14.md) -- the THIRD
    // real texture layer, proving the array-texture mechanism scales past
    // two packs, not just two packs' pieces repeated.
    name: "kenney-city-kit-commercial",
    path: "public/vendor/kits/kenney-city-kit-commercial/Textures/colormap.png",
    usedBy: ["building-a.glb", "building-e.glb", "building-f.glb", "building-j.glb", "building-skyscraper-b.glb", "detail-awning.glb", "detail-parasol-a.glb"],
  },
  {
    name: "ground-grass",
    path: "public/vendor/textures/grass/diffuse.webp",
    usedBy: ["ground plane (procedural, not a pack mesh)"],
  },
  {
    // RB5 (docs/specs/REBUILD-CHECKLIST.md, THE CONVERGENCE): Mark's own
    // read of 13-street-level.png -- "buildings in a dust bowl". Measured,
    // not assumed: layer 3 (ground-grass)'s own mean RGB is (172,148,121)
    // -- a warm dirt/sand tone despite its own filename, not green. A real
    // fix needs a second, more neutral ground texture for the paved area
    // near buildings/roads, not just darkening the same dirt texture
    // further. Already-vendored, already CC0-licensed (public/vendor/
    // textures/gravel/LICENSE.txt) -- no new asset sourcing needed.
    // Measured mean RGB (173,163,150) -- notably more neutral/grey than
    // grass's own (172,148,121), close to plaster's (171,163,160) without
    // that texture's own wall-surface patterning reading oddly as ground.
    name: "ground-paved",
    path: "public/vendor/textures/gravel/diffuse.webp",
    usedBy: ["ground plane, near buildings/roads (procedural, not a pack mesh) -- RB5"],
  },
];

mkdirSync(OUT_DIR, { recursive: true });

const manifest = { _comment: "GENERATED by scripts/normalise-kit-textures.mjs -- do not edit by hand.", targetSize: TARGET_SIZE, layers: [] };

for (let i = 0; i < SOURCES.length; i++) {
  const src = SOURCES[i];
  const srcPath = join(ROOT, src.path);
  const outName = `${String(i).padStart(2, "0")}-${src.name}.png`;
  const outPath = join(OUT_DIR, outName);
  const before = await sharp(srcPath).metadata();
  await sharp(srcPath)
    .resize(TARGET_SIZE, TARGET_SIZE, { fit: "fill" })
    .ensureAlpha()
    .png()
    .toFile(outPath);
  const after = await sharp(outPath).metadata();
  manifest.layers.push({
    index: i,
    file: outName,
    sourcePath: src.path,
    sourceFormat: before.format,
    sourceSize: `${before.width}x${before.height}`,
    normalisedFormat: after.format,
    normalisedSize: `${after.width}x${after.height}`,
    usedBy: src.usedBy,
  });
  console.log(`layer ${i}: ${src.path} (${before.format} ${before.width}x${before.height}) -> ${outName} (${after.format} ${after.width}x${after.height})`);
}

writeFileSync(join(OUT_DIR, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`\nwrote ${SOURCES.length} normalised layers + manifest.json to ${OUT_DIR}`);
